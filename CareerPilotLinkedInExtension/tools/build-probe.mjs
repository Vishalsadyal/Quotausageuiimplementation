// Builds the paste-into-console probes from the same detection code the extension uses,
// so they can never drift from the extension:
//   tools/linkedin-tile-probe.js  - snapshot: which detection strategies work on this page
//   tools/linkedin-walk-probe.js  - dry run: opens every tile, pages through results, runs searches (never applies)
import { readFileSync, writeFileSync } from "fs";
import { dirname, resolve } from "path";
import { fileURLToPath } from "url";

const here = dirname(fileURLToPath(import.meta.url));
const dom = readFileSync(resolve(here, "../src/linkedin-dom.js"), "utf8");

const fresh = `// Force a fresh copy of the resolver even if the extension already loaded one on this page.
delete window.CPLinkedInDom;
`;

const tileHeader = `/*
 * AutoApply CV - LinkedIn job tile probe (GENERATED by tools/build-probe.mjs, do not edit).
 *
 * Paste this whole file into the DevTools console on a LinkedIn Jobs search page.
 * It runs every detection strategy the extension uses and shows which ones work:
 *   tiles     → known-classes, data-attributes, job-ref-attributes, job-links, repeated-list, tile-words
 *   job id    → data-attr, job-ref-attr, link, numeric-attr, selected-url, text-hash
 *   applied   → footer-classes, leaf-text, text-lines, aria-label, status-attribute
 *   detail    → known-classes, data-view-name, apply-button, job-heading, scroll-column
 * Outlines: green = applied, orange = not applied, red = no stable job id, dashed = detail pane.
 * The report is copied to the clipboard and kept in window.__cpProbe. cpProbeClear() removes outlines.
 */
`;

const walkHeader = `/*
 * AutoApply CV - LinkedIn walk probe (GENERATED by tools/build-probe.mjs, do not edit).
 *
 * A DRY RUN of the auto-apply flow. It NEVER applies or submits anything.
 * Paste into the DevTools console on a LinkedIn Jobs search page (pause the extension's run first).
 * It opens every job tile, reads the details panel, moves to the next results page and through
 * your search terms, then prints tables and copies a JSON report to the clipboard.
 * Edit CONFIG near the top of the walk section (search terms, pages, open Easy Apply form) before pasting.
 * Stop any time with cpWalkStop(). Tile labels: green = applied, blue = Easy Apply, orange = other, purple = never fully loaded, red = did not open.
 */
`;

writeFileSync(resolve(here, "linkedin-tile-probe.js"), `${tileHeader}${fresh}\n${dom}\n${readFileSync(resolve(here, "probe-report.js"), "utf8")}`);
writeFileSync(resolve(here, "linkedin-walk-probe.js"), `${walkHeader}${fresh}\n${dom}\n${readFileSync(resolve(here, "walk-report.js"), "utf8")}`);
console.log("Wrote tools/linkedin-tile-probe.js and tools/linkedin-walk-probe.js");
